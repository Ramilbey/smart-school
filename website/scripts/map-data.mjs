// Generates src/mapdata.js: dotted maps from the real Natural Earth outlines (via world-atlas).
//   node scripts/map-data.mjs
// UZ     hex-grid dots inside Uzbekistan (10m outline), then the edge dots
// NEIGH  sparse dots in the neighbouring countries
// GLOBE  land dots on a sphere (110m land) with a flag for the ones inside Uzbekistan
// Coordinates are stored as Int16 pairs: (lon - 50) * 400 and (lat - 30) * 400, base64 encoded.
// GLOBE is the exception (it covers the whole world): lon * 100 and lat * 100.
import fs from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { feature } = require('topojson-client');
const countries = require('world-atlas/countries-10m.json');
const land110 = require('world-atlas/land-110m.json');

const polys = (g) => (g.type === 'Polygon' ? [g.coordinates] : g.coordinates);
const prep = (list) => list.map((rings) => {
  let x0 = 1e9, x1 = -1e9, y0 = 1e9, y1 = -1e9;
  for (const [x, y] of rings[0]) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
  return { rings, x0, x1, y0, y1 };
});
const inside = (P, lon, lat) => {
  for (const p of P) {
    if (lon < p.x0 || lon > p.x1 || lat < p.y0 || lat > p.y1) continue;
    let c = false;
    for (const ring of p.rings) {
      for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
        const [xi, yi] = ring[i], [xj, yj] = ring[j];
        if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) c = !c;
      }
    }
    if (c) return true;
  }
  return false;
};

const feats = feature(countries, countries.objects.countries).features;
const named = (n) => polys(feats.find((f) => f.properties.name === n).geometry);
const UZP = prep(named('Uzbekistan'));
const NEP = prep(['Kazakhstan', 'Turkmenistan', 'Kyrgyzstan', 'Tajikistan', 'Afghanistan', 'Iran', 'China', 'Pakistan', 'Russia'].flatMap(named));
const LANDP = prep(polys(feature(land110, land110.objects.land).geometry ?? feature(land110, land110.objects.land).features[0].geometry));

const enc = (arr) => Buffer.from(new Int16Array(arr).buffer).toString('base64');
const q = (lon, lat) => [Math.round((lon - 50) * 400), Math.round((lat - 30) * 400)];
/* the whole world does not fit that scale (it only reaches lon -32 to 132), so the globe uses plain hundredths of a degree */
const qw = (lon, lat) => [Math.round(lon * 100), Math.round(lat * 100)];

/* Uzbekistan: hex grid, 0.06 degrees between rows */
const dLat = 0.0532, dLon = 0.0818;
const uz = [], edge = [];
for (let r = 0, lat = 37.0; lat < 45.8; r++, lat += dLat) {
  for (let lon = 55.8 + (r % 2 ? dLon / 2 : 0); lon < 73.4; lon += dLon) {
    if (!inside(UZP, lon, lat)) continue;
    let isEdge = false;
    for (const [ox, oy] of [[dLon, 0], [-dLon, 0], [dLon / 2, dLat], [-dLon / 2, dLat], [dLon / 2, -dLat], [-dLon / 2, -dLat]]) {
      if (!inside(UZP, lon + ox, lat + oy)) { isEdge = true; break; }
    }
    (isEdge ? edge : uz).push(...q(lon, lat));
  }
}
/* neighbours: sparse */
const ne = [];
for (let r = 0, lat = 34.2; lat < 49; r++, lat += 0.13) {
  for (let lon = 52.5 + (r % 2 ? 0.1 : 0); lon < 77.5; lon += 0.2) {
    if (!inside(UZP, lon, lat) && inside(NEP, lon, lat)) ne.push(...q(lon, lat));
  }
}
/* globe: rows of dots by latitude (cleaner than a spiral near the poles), land only */
const globe = [], flags = [];
const STEP = 0.5; // degrees between rows and, on the equator, between dots
for (let r = 0, lat = -89.5; lat < 90; r++, lat += STEP) {
  const n = Math.max(1, Math.round((360 * Math.cos((lat * Math.PI) / 180)) / STEP));
  for (let i = 0; i < n; i++) {
    const lon = -180 + ((i + (r % 2 ? 0.5 : 0)) * 360) / n;
    if (!inside(LANDP, lon, lat)) continue;
    globe.push(...qw(lon, lat));
    flags.push(inside(UZP, lon, lat) ? 1 : 0);
  }
}
const out = `// Generated by scripts/map-data.mjs from Natural Earth (world-atlas). Do not edit by hand.
// Int16 pairs: (lon - 50) * 400, (lat - 30) * 400. Base64. GLOBE: lon * 100, lat * 100.
export const UZ = '${enc(uz)}';
export const UZ_EDGE = '${enc(edge)}';
export const NEIGH = '${enc(ne)}';
export const GLOBE = '${enc(globe)}';
export const GLOBE_UZ = '${Buffer.from(new Uint8Array(flags)).toString('base64')}';
`;
fs.writeFileSync(new URL('../src/mapdata.js', import.meta.url), out);
console.log({ uz: uz.length / 2, edge: edge.length / 2, neigh: ne.length / 2, globe: globe.length / 2, kb: Math.round(out.length / 1024) });
